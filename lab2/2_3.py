print("-" * 40)

# Подставляем все возможные цифры от 0 до 9 вместо двух символов '?' в маске 12345?7?8
for d1 in '0123456789':
    for d2 in '0123456789':
        num = int(f"12345{d1}7{d2}8")
        
        # Проверяем, что число не превышает 10^9 и делится на 23 без остатка
        if num <= 10**9 and num % 23 == 0:
            print(f"{num:<15} | {num // 23}")
